// Number of characters of a UTF-8 literal (accented letters count once).
constexpr size_t ui_chars(const char* s, size_t i = 0, size_t n = 0) {
    return s[i] == '\0' ? n : ui_chars(s, i + 1, n + (((static_cast<unsigned char>(s[i]) & 0xC0) != 0x80) ? 1 : 0));
}

#define UI_FITS(text, max_chars) static_assert(ui_chars(text) <= (max_chars), "display text too long: " #text)

