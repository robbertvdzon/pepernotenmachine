#!/usr/bin/env python3
"""Converts the splash artwork (any image PIL can read, 160 px wide) into a static RGB565 bitmap for flash.

Usage:  python3 tools/make_splash_art.py path/to/art.jpeg

Writes
  src/splash_art.cpp      const uint16_t splash_art_pixels[W*H]   (native little-endian RGB565, row after row, no padding)
  include/splash_art.h    size, and the background color of the rest of the splash screen

The splash screen background below the picture is the color of the picture's bottom row (median), converted exactly like the
pixels, so the picture melts into it without a seam. Needs Pillow (pip install pillow).
(The LVGL 8 online converter output, lv_img_dsc_t / indexed, does not work with LVGL 9: convert from the original image instead.)
"""
import os
import statistics
import sys

from PIL import Image

if len(sys.argv) != 2:
    sys.exit(__doc__)
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
im = Image.open(sys.argv[1]).convert("RGB")
w, h = im.size
if w != 160:
    sys.exit("the picture must be exactly 160 px wide (it is %d)" % w)


def to565(r, g, b):  # rounded, not truncated: smoother gradients
    return ((r * 31 + 127) // 255) << 11 | ((g * 63 + 127) // 255) << 5 | ((b * 31 + 127) // 255)


def expand(v):  # 565 -> 8 bit per channel such that the panel's truncation gives v back
    r, g, b = (v >> 11) & 31, (v >> 5) & 63, v & 31
    return (r << 3 | r >> 2) << 16 | (g << 2 | g >> 4) << 8 | (b << 3 | b >> 2)


px = im.load()
vals = [to565(*px[x, y]) for y in range(h) for x in range(w)]
bottom = [to565(*px[x, h - 1]) for x in range(w)]
bg565 = int(statistics.median_low(bottom))
bg_hex = expand(bg565)

with open(os.path.join(root, "src", "splash_art.cpp"), "w") as f:
    f.write("// Generated by tools/make_splash_art.py from the owner's artwork. Do not edit.\n")
    f.write('#include "splash_art.h"\n\n')
    f.write("const uint16_t splash_art_pixels[SPLASH_ART_W * SPLASH_ART_H] = {\n")
    for y in range(h):
        f.write("    " + ",".join("0x%04x" % v for v in vals[y * w:(y + 1) * w]) + ",\n")
    f.write("};\n")
with open(os.path.join(root, "include", "splash_art.h"), "w") as f:
    f.write("// Generated by tools/make_splash_art.py. Do not edit.\n#pragma once\n\n#include <stdint.h>\n\n")
    f.write("constexpr int SPLASH_ART_W = %d, SPLASH_ART_H = %d;\n" % (w, h))
    f.write("// Background of the rest of the splash screen = the picture's bottom row (RGB565 and the same color as 0xRRGGBB).\n")
    f.write("constexpr uint16_t SPLASH_ART_BG_565 = 0x%04x;\nconstexpr uint32_t SPLASH_ART_BG_HEX = 0x%06x;\n\n" % (bg565, bg_hex))
    f.write("// %d x %d pixels, RGB565, %d bytes, in flash.\nextern const uint16_t splash_art_pixels[SPLASH_ART_W * SPLASH_ART_H];\n" % (w, h, w * h * 2))
print("%dx%d, background 0x%06x (RGB565 0x%04x), bottom row has %d distinct values" % (w, h, bg_hex, bg565, len(set(bottom))))
